#!/usr/bin/env python3
"""Cochilo's design build: three layers in, one CTokens.kt out (design/README.md).

    python3 design/build.py          # write app/src/main/java/br/gabriel/cochilo/ui/theme/CTokens.kt
    python3 design/build.py --check  # the checks, and fail if CTokens.kt isn't what the layers make

The layers:
  design/core/                 the Gabriel Design System's core, vendored at a pinned version
                               (core.json + its scripts, unchanged; see design/core/CORE.md)
  design/brand/tata-slings/    the Tatá Slings brand (brand.json): colour roles and the type family
  design/product/cochilo/      Cochilo's own layer (layer.json): its tokens and contrast pairs

They are put together as the core's generator expects one tokens file, then the core's own code
writes Kotlin and runs its checks (layers, brand limits, contrast in light, dark and night). So
Cochilo never forks the generator: re-syncing the core is copying its files in.
"""
import json
import pathlib
import sys

DESIGN = pathlib.Path(__file__).resolve().parent
REPO = DESIGN.parent
sys.path.insert(0, str(DESIGN / "core" / "scripts"))

import check_tokens  # noqa: E402  (the core's checks)
import gen_tokens  # noqa: E402  (the core's generator)

APP_TOKENS = REPO / "app/src/main/java/br/gabriel/cochilo/ui/theme/CTokens.kt"
BRAND = "tata-slings"
LAYER = "cochilo"


def read(path):
    return json.loads(path.read_text())


def assemble():
    """The three layers as one tokens document, the shape the core's scripts read."""
    core = read(DESIGN / "core" / "core.json")
    brand = read(DESIGN / "brand" / BRAND / "brand.json")
    product = read(DESIGN / "product" / LAYER / "layer.json")
    version = (DESIGN / "VERSION").read_text().strip()
    return {
        "name": "Cochilo design",
        "version": f"{version} (core {core['version']})",
        "core": core["core"],
        "layers": {LAYER: product["layer"]},
        "brands": {k: v for k, v in brand.items() if not k.startswith("$")},
        "variants": {},
        "contrast": product["contrast"],
    }


def kotlin(t):
    # The core's Cochilo writer, with a header that says where these values now come from.
    gen_tokens.HEADER = ("GENERATED by Cochilo design/build.py from design/ (Gabriel Design System core + "
                         "Tatá Slings brand + Cochilo layer) v{v} — do not edit.")
    return gen_tokens.cochilo_kt(t)


def checks(t):
    check_tokens.check_layers(t)
    check_tokens.check_brands(t)
    check_tokens.check_contrast(t)
    return check_tokens.errors, check_tokens.warnings


def main():
    t = assemble()
    errors, warnings = checks(t)
    for w in warnings:
        print("warning:", w)
    for e in errors:
        print("error:", e)
    text = kotlin(t)
    if "--check" in sys.argv:
        if not APP_TOKENS.exists() or APP_TOKENS.read_text() != text:
            errors.append(f"{APP_TOKENS.relative_to(REPO)} differs from what design/ makes: run python3 design/build.py")
            print("error:", errors[-1])
        print("design check:", "failed" if errors else "ok", f"({len(errors)} error(s), {len(warnings)} warning(s))")
        return 1 if errors else 0
    if errors:
        print("not written: fix the errors first")
        return 1
    if not APP_TOKENS.exists() or APP_TOKENS.read_text() != text:
        APP_TOKENS.write_text(text)
        print("wrote", APP_TOKENS.relative_to(REPO))
    else:
        print("CTokens.kt is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
