// Cochilo on the watch (0.53.0, docs/wear.md): one tile with Start sleep / Woke up and the two
// breasts, for when both hands hold the baby. It shares the phone's application id and signing
// key, as Google's wearable services require for the two to talk.
plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("app.cash.paparazzi")
}

android {
    namespace = "br.gabriel.cochilo.wear"
    compileSdk = 35

    defaultConfig {
        applicationId = "br.gabriel.cochilo"
        minSdk = 30
        targetSdk = 35
        versionCode = (project.findProperty("appVersionCode") as String?)?.toIntOrNull() ?: 1
        versionName = (project.findProperty("appVersionName") as String?) ?: "0.1.0"
    }

    signingConfigs {
        create("release") {
            // The phone's key (app/build.gradle.kts): the watch app must be signed the same way.
            val env = { k: String -> System.getenv(k)?.takeIf { it.isNotEmpty() } }
            // A relative path means the same file the phone's build reads, under app/.
            storeFile = env("RELEASE_STORE_FILE")?.let { if (File(it).isAbsolute) file(it) else file("../app/$it") } ?: file("../app/cochilo-test.keystore")
            storePassword = env("RELEASE_STORE_PASSWORD") ?: "android"
            keyAlias = env("RELEASE_KEY_ALIAS") ?: "cochilo"
            keyPassword = env("RELEASE_KEY_PASSWORD") ?: "android"
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.getByName("release")
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    // The design's tokens and the wire format come from the phone's own sources, so the watch
    // can't drift: CTokens (generated by design/build.py) and WearWire, copied in at build time.
    sourceSets["main"].java.srcDir(layout.buildDirectory.dir("generated/shared"))

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    lint { checkReleaseBuilds = false }
}

val shared = tasks.register<Copy>("copyShared") {
    from("../app/src/main/java") {
        include("br/gabriel/cochilo/ui/theme/CTokens.kt", "br/gabriel/cochilo/wear/WearWire.kt")
    }
    into(layout.buildDirectory.dir("generated/shared"))
}
tasks.matching { it.name.startsWith("compile") || it.name.startsWith("ksp") }.configureEach { dependsOn(shared) }

dependencies {
    implementation("androidx.wear.tiles:tiles:1.4.1")
    implementation("androidx.wear.protolayout:protolayout:1.2.1")
    implementation("androidx.wear.protolayout:protolayout-material:1.2.1")
    implementation("androidx.concurrent:concurrent-futures:1.2.0")
    implementation("com.google.android.gms:play-services-wearable:19.0.0")
    implementation("org.jetbrains.kotlinx:kotlinx-coroutines-android:1.9.0")
    implementation("org.jetbrains.kotlinx:kotlinx-coroutines-play-services:1.9.0")
    // CTokens is written against Compose's Color and dp; only those two small libraries.
    implementation(platform("androidx.compose:compose-bom:2024.06.00"))
    implementation("androidx.compose.ui:ui-graphics")
    implementation("androidx.compose.ui:ui-unit")
    // The tile's screenshot (docs/wear.md): the real renderer, drawn by Paparazzi.
    testImplementation("junit:junit:4.13.2")
    // debug only, so its resources reach the test; the release watch app doesn't carry it.
    debugImplementation("androidx.wear.tiles:tiles-renderer:1.4.1")
    debugImplementation("com.google.guava:guava:33.3.1-android")
}

kotlin { compilerOptions { jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17) } }
